DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists
  FROM USER_TABLES
  WHERE TABLE_NAME = 'USER_GAME_JOURNAL_PREFS';

  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE USER_GAME_JOURNAL_PREFS (
        USER_ID VARCHAR2(30) NOT NULL,
        GAMEDB_GAME_ID NUMBER NOT NULL,
        IS_ENABLED NUMBER(1,0) DEFAULT 0 NOT NULL,
        DEFAULT_IS_PUBLIC NUMBER(1,0) DEFAULT 0 NOT NULL,
        CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_USER_GAME_JOURNAL_PREFS PRIMARY KEY (USER_ID, GAMEDB_GAME_ID),
        CONSTRAINT CK_UGJP_ENABLED CHECK (IS_ENABLED IN (0,1)),
        CONSTRAINT CK_UGJP_DEFAULT_PUBLIC CHECK (DEFAULT_IS_PUBLIC IN (0,1)),
        CONSTRAINT FK_UGJP_GAME FOREIGN KEY (GAMEDB_GAME_ID) REFERENCES GAMEDB_GAMES (GAME_ID)
      )';
  END IF;

  SELECT COUNT(*) INTO v_exists
  FROM USER_TABLES
  WHERE TABLE_NAME = 'USER_GAME_JOURNAL_ENTRIES';

  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE USER_GAME_JOURNAL_ENTRIES (
        ENTRY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        USER_ID VARCHAR2(30) NOT NULL,
        GAMEDB_GAME_ID NUMBER NOT NULL,
        ENTRY_TITLE VARCHAR2(120),
        ENTRY_BODY VARCHAR2(2000) NOT NULL,
        IS_PUBLIC NUMBER(1,0) DEFAULT 0 NOT NULL,
        CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT CK_UGJE_PUBLIC CHECK (IS_PUBLIC IN (0,1)),
        CONSTRAINT FK_UGJE_GAME FOREIGN KEY (GAMEDB_GAME_ID) REFERENCES GAMEDB_GAMES (GAME_ID)
      )';
  END IF;

  SELECT COUNT(*) INTO v_exists
  FROM USER_INDEXES
  WHERE INDEX_NAME = 'IX_UGJE_USER_GAME_CREATED';

  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE INDEX IX_UGJE_USER_GAME_CREATED
      ON USER_GAME_JOURNAL_ENTRIES (USER_ID, GAMEDB_GAME_ID, CREATED_AT DESC)';
  END IF;
END;
/
